/*
 * Pin the daily climbs: write js/data-daily.js, the list of which seven
 * prompts each day gets.
 *
 *   node tools/build-daily.js
 *
 * The engine can work the schedule out by itself, but its choices depend on
 * the whole pool of prompts, so adding or removing one would reshuffle every
 * day, today included. Pinning stops that. Run this after changing the
 * prompts: days up to tomorrow are kept exactly as they are, because people
 * have played them, and every later day is worked out afresh so that new
 * prompts join the rotation.
 */
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'js', 'data-daily.js');
const START = '2026-11-11'; // day 1
const AHEAD = 400; // days pinned beyond today

for (const f of ['data-lists', 'data-geo', 'data-elements', 'data-tails']) require(`../js/${f}.js`);
if (fs.existsSync(OUT)) require(OUT);
const D = globalThis.GAME_DATA;
if (!D.daily) D.daily = { start: START, days: [] };

// Today's day number, as the engine counts it: whole UTC days since the start.
const [y, m, d] = D.daily.start.split('-').map(Number);
const today = Math.max(1, Math.floor((Date.now() - Date.UTC(y, m - 1, d)) / 86400000) + 1);

// Keep what has been played; let the engine choose the rest again.
const kept = Math.min(D.daily.days.length, today + 1);
D.daily.days = D.daily.days.slice(0, kept);
require('../js/engine.js');
const O = globalThis.GAME;

const last = today + AHEAD;
const dateOf = (n) => new Date(Date.UTC(y, m - 1, d + n - 1)).toISOString().slice(0, 10);
const lines = [];
for (let n = 1; n <= last; n++) lines.push(`      '${O.promptsForDay(n).map((p) => p.id).join(' ')}', // ${n} · ${dateOf(n)}`);

fs.writeFileSync(
  OUT,
  `/*
 * GENERATED by tools/build-daily.js. Do not edit by hand.
 *
 * The daily climbs: the seven prompts for each day, counted from \`start\`.
 * Pinned here so that changing the prompts never reshuffles a day that has
 * been played. Past the end of the list the engine chooses for itself.
 */
(function (root) {
  const D = (root.GAME_DATA = root.GAME_DATA || {});
  D.daily = {
    start: '${D.daily.start}',
    days: [
${lines.join('\n')}
    ],
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
`
);
console.log(`${last} days pinned (${kept} kept as they were, ${last - kept} chosen now); today is day ${today}`);
